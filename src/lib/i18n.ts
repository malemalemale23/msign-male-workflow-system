export type TKey = keyof typeof dict;

export function translate(
  locale: Locale,
  key: TKey,
  vars?: Record<string, string>
) {
  let text: string = dict[key][locale];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
